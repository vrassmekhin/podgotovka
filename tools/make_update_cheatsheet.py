def markup_to_html(text):
    text = (text or "").strip()
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    out = []
    for b in re.split(r"\n\s*\n", text):
        lines = b.split("\n")
        if any(l.strip() for l in lines) and all(re.match(r"^\s*[-•]\s+", l) or not l.strip() for l in lines):
            for l in lines:
                if l.strip():
                    out.append(("li", "• " + re.sub(r"^\s*[-•]\s+", "", l)))
        else:
            out.append(("p", b.replace("\n", "<br/>")))
    return out


def build_flowables(ticket, fs):
    num, qs = ticket
    lead = fs + 1.2
    h_title = ParagraphStyle("t", fontName="DJ-B", fontSize=fs + 2, leading=fs + 3,
                             textColor=ACCENT, spaceAfter=fs * 0.5)
    h_q = ParagraphStyle("q", fontName="DJ-B", fontSize=fs + 0.3, leading=lead,
                         textColor=black, spaceBefore=fs * 0.6, spaceAfter=fs * 0.2)
    body = ParagraphStyle("b", fontName="DJ", fontSize=fs, leading=lead,
                          textColor=HexColor("#1c2433"), alignment=TA_LEFT, spaceAfter=fs * 0.2)
    sub_body = ParagraphStyle("sb", parent=body, leftIndent=fs * 0.6, textColor=HexColor("#333333"))
    fl = [P("Билет № %d" % num, h_title)]
    for i, (q, a) in enumerate(qs, 1):
        fl.append(P("%d. %s" % (i, q), h_q))
        for kind, para in markup_to_html(a):
            fl.append(P(para, sub_body if kind == "li" else body))
    return fl


def fits(flowables, w, h):
    total = 0
    for f in flowables:
        _, fh = f.wrap(w, h)
        total += fh
        if total > h:
            return False
    return total <= h


def fit_font(ticket, w, h):
    lo, hi, best = 3.0, 8.0, 3.0
    for _ in range(18):
        mid = (lo + hi) / 2
        if fits(build_flowables(ticket, mid), w, h):
            best, lo = mid, mid
        else:
            hi = mid
    return best


def draw_cut_guides(c):
    c.saveState()
    c.setStrokeColor(HexColor("#9aa3b2"))
    c.setLineWidth(0.4)
    c.setDash(2, 2)
    for i in range(COLS + 1):
        x = MARGIN + i * CARD_W
        c.line(x, MARGIN, x, PAGE_H - MARGIN)
    for j in range(ROWS + 1):
        y = MARGIN + j * CARD_H
        c.line(MARGIN, y, PAGE_W - MARGIN, y)
    c.restoreState()
    c.setDash()
    c.setFillColor(HexColor("#9aa3b2"))
    c.setFont("DJ", 6)
    c.drawString(MARGIN, PAGE_H - MARGIN + 2.5, "режьте по пунктиру")


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "Билеты_11-19_обновлённые.pdf"
    c = canvas.Canvas(out_path, pagesize=A4)
    c.setTitle("Обновлённые ответы — билеты 11–19 (История России)")
    inner_w, inner_h = CARD_W - 2 * CARD_PAD, CARD_H - 2 * CARD_PAD
    per_page = COLS * ROWS
    for idx, ticket in enumerate(TICKETS):
        pos = idx % per_page
        if pos == 0:
            if idx > 0:
                c.showPage()
            draw_cut_guides(c)
        col, row = pos % COLS, pos // COLS
        x0 = MARGIN + col * CARD_W
        y_top = PAGE_H - MARGIN - row * CARD_H
        fx, fy = x0 + CARD_PAD, y_top - CARD_H + CARD_PAD
        fs = fit_font(ticket, inner_w, inner_h)
        kif = KeepInFrame(inner_w, inner_h, build_flowables(ticket, fs), mode="shrink")
        Frame(fx, fy, inner_w, inner_h, leftPadding=0, rightPadding=0,
              topPadding=0, bottomPadding=0, showBoundary=0).addFromList([kif], c)
    c.showPage()
    c.save()
